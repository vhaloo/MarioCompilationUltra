"""Validate ten UTF-8 catalogs and reproduce the compiled translation table."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    directory = ROOT / 'assets/locales'
    languages = json.loads((directory / 'languages.json').read_text(encoding='utf8'))
    assert len(languages) == 10 and languages[0]['code'] == 'en' and languages[1]['code'] == 'fr'
    catalogs = [json.loads((directory / (lang['code'] + '.json')).read_text(encoding='utf8')) for lang in languages]
    keys = sorted(catalogs[0])
    for lang, catalog in zip(languages, catalogs):
        assert set(catalog) == set(keys), f"Missing or unexpected messages: {lang['code']}"
        assert all(isinstance(value, str) and value.strip() for value in catalog.values())
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    content = '// Generated by tools/localization.py. Edit assets/locales/*.json.\n'
    content += 'static const Locale Locales[LocaleCount] = {\n'
    content += ''.join('    {' + quote(lang['code']) + ', ' + quote(lang['name']) + '},\n' for lang in languages) + '};\n'
    content += 'struct Message { const char *key; const char *text[LocaleCount]; };\nstatic const Message Messages[] = {\n'
    content += ''.join('    {' + quote(key) + ', {' + ', '.join(quote(catalog[key]) for catalog in catalogs) + '}},\n' for key in keys) + '};\n'
    target = ROOT / 'src/locales.inc'
    if args.check:
        assert target.read_text(encoding='utf8') == content, 'Run python tools/localization.py'
    else:
        target.write_text(content, encoding='utf8', newline='\n')
    print(f'{len(languages)} catalogs, {len(keys)} messages each; compiled table verified')
if __name__ == '__main__':
    main()
